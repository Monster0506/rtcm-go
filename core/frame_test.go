package core

import (
	"strings"
	"testing"
)

func TestParseFrame(t *testing.T) {
	tests := []struct {
		name         string
		data         []byte
		wantErr      bool
		wantErrText  string
		wantPayload  []byte
		wantConsumed int
	}{
		{
			name:         "valid frame",
			data:         []byte{0xd3, 0x00, 0x04, 0x4c, 0xe0, 0x00, 0x80, 0xed, 0xed, 0xd6},
			wantPayload:  []byte{0x4c, 0xe0, 0x00, 0x80},
			wantConsumed: 10,
		},
		{
			name: "bad CRC",
			data: []byte{
				0xd3, 0x00, 0x13, 0x3e, 0xd0, 0x01, 0x03, 0x8a, 0x58, 0xd9,
				0x49, 0x3c, 0x87, 0x2f, 0x34, 0x10, 0x9d, 0x07, 0xd6, 0xaf,
				0x48, 0x20, 0x5a, 0xd7, 0xf7,
			},
			wantErr:      true,
			wantConsumed: 25,
		},
		{
			name: "premature EOF",
			data: []byte{
				0xd3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3,
				0xa3, 0xa3, 0xa3, 0xa3, 0xd3, 0x00, 0x48, 0x3f, 0x10, 0x00,
				0x86, 0x85, 0x03, 0x14, 0x00, 0x24, 0x34, 0x07, 0xba, 0x41,
				0x74, 0x0b, 0xfa, 0xca,
			},
			wantErr:      true,
			wantErrText:  "72 bytes requested, 17 bytes returned",
			wantConsumed: 0,
		},
		{
			name:         "zero-length payload",
			data:         []byte{0xd3, 0x00, 0x00},
			wantErr:      true,
			wantErrText:  "invalid payload size 0 bytes",
			wantConsumed: 0,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			payload, consumed, err := ParseFrame(tt.data)
			if (err != nil) != tt.wantErr {
				t.Fatalf("err = %v, wantErr %v", err, tt.wantErr)
			}
			if tt.wantErrText != "" && !strings.Contains(err.Error(), tt.wantErrText) {
				t.Fatalf("err = %q, want it to contain %q", err.Error(), tt.wantErrText)
			}
			if consumed != tt.wantConsumed {
				t.Fatalf("consumed = %d, want %d", consumed, tt.wantConsumed)
			}
			if err != nil {
				return
			}
			if len(payload) != len(tt.wantPayload) {
				t.Fatalf("payload = %v, want %v", payload, tt.wantPayload)
			}
			for i := range payload {
				if payload[i] != tt.wantPayload[i] {
					t.Fatalf("payload[%d] = %#x, want %#x", i, payload[i], tt.wantPayload[i])
				}
			}
		})
	}
}

func TestParseFrameResync(t *testing.T) {
	stream := []byte{
		0xd3, 0x00, 0x13, 0x3e, 0xd0, 0x00, 0x03, 0x84, 0x1a, 0x86, 0x92, 0xbf, 0xb4, 0x4b, 0x4b,
		0xf4, 0xfa, 0xb7, 0xdc, 0x37, 0x62, 0x8a, 0x33, 0x84, 0x79,
		0xd3, 0x00, 0x15, 0x3e, 0xe0, 0x00, 0x03, 0x84, 0x1a, 0x86, 0x92, 0xbf, 0xb4, 0x4b, 0x4b,
		0xf4, 0xfa, 0xb7, 0xdc, 0x37, 0x62, 0x8a, 0x01, 0x57, 0x1b, 0xa9, 0xd6,
		0xd3, 0x00, 0x19, 0x3e, 0xf0, 0x00, 0x14, 0x53, 0x45, 0x50, 0x43, 0x48, 0x4f, 0x4b, 0x45,
		0x5f, 0x42, 0x33, 0x45, 0x36, 0x20, 0x20, 0x20, 0x53, 0x50, 0x4b, 0x45, 0x00, 0x07, 0x6e, 0x66,
		0xd3, 0x00, 0x1e, 0x3f, 0x00, 0x00, 0x14, 0x53, 0x45, 0x50, 0x43, 0x48, 0x4f, 0x4b, 0x45,
		0x5f, 0x42, 0x33, 0x45, 0x36, 0x20, 0x20, 0x20, 0x53, 0x50, 0x4b, 0x45, 0x00, 0x04, 0x35,
		0x38, 0x35, 0x36, 0xff, 0x68, 0x94,
		0xd3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3, 0xa3,
		0xd3, 0x00, 0x48, 0x3f, 0x10, 0x00, 0x86, 0x85, 0x03, 0x14, 0x00, 0x24, 0x34, 0x07, 0xba,
		0x41, 0x74, 0x0b, 0xfa, 0xc2, 0x20, 0x33, 0x11, 0x3d, 0xa0, 0x2b, 0xfb, 0x04, 0xb8, 0x71,
		0x80, 0xc0, 0xbd, 0xdf, 0xf9, 0x06, 0xb8, 0xd7, 0x55, 0x80, 0x75, 0xbb, 0xf8, 0xe6, 0x20,
		0xc5, 0x18, 0x3d, 0x23, 0xb7, 0xfa, 0xe5, 0x5c, 0x85, 0xd8, 0x80, 0x5c, 0x83, 0xf9, 0x40,
		0x6d, 0x8d, 0x25, 0x01, 0xb1, 0x37, 0xf9, 0x22, 0xbd, 0x7a, 0xc2, 0x81, 0x68, 0x03, 0xf8,
		0x9f, 0xc6, 0xe6,
	}
	wantLens := []int{25, 27, 31, 36, 78}
	for i, wantLen := range wantLens {
		_, consumed, err := ParseFrame(stream)
		if err != nil {
			t.Fatalf("message %d: unexpected error: %v", i, err)
		}
		gotLen := consumed
		if i == 4 {
			gotLen -= 14
		}
		if gotLen != wantLen {
			t.Fatalf("message %d: consumed=%d, want %d", i, consumed, wantLen)
		}
		stream = stream[consumed:]
	}
	if len(stream) != 0 {
		t.Fatalf("stream not fully consumed: %d bytes left", len(stream))
	}
}
