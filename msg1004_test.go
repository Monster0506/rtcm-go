package rtcm

import "testing"

func TestDecodeMsg1004(t *testing.T) {
	frame := []byte{
		0xd3, 0x00, 0xb4, 0x3e, 0xc0, 0x00, 0x4c, 0x0a, 0xdb, 0xa2, 0xb0, 0x09,
		0xae, 0x63, 0xb1, 0xe1, 0xde, 0x7f, 0xd2, 0xeb, 0x30, 0x68, 0x7a, 0x9c,
		0x7b, 0xfb, 0xe8, 0x60, 0x54, 0x15, 0x9f, 0x99, 0x3e, 0xfe, 0x8d, 0x8d,
		0x83, 0x17, 0xf3, 0x64, 0x5f, 0xf4, 0x15, 0x06, 0x93, 0x2c, 0x73, 0xad,
		0xc7, 0xf4, 0xf9, 0xac, 0x30, 0x2d, 0xe7, 0x6b, 0xfe, 0x9c, 0x21, 0xb9,
		0xbc, 0x64, 0x02, 0xe4, 0x7f, 0xa1, 0xe2, 0x60, 0x8b, 0x01, 0xdb, 0xb7,
		0xfa, 0xf2, 0x49, 0x17, 0xfa, 0xe0, 0x79, 0x23, 0xfd, 0x1f, 0x03, 0x06,
		0x1c, 0x24, 0x45, 0x3f, 0xe5, 0x0c, 0x09, 0xff, 0x91, 0x01, 0x63, 0x0f,
		0xe9, 0xd3, 0xf8, 0x47, 0xe0, 0xf7, 0x8f, 0xfe, 0x3d, 0x30, 0x85, 0x31,
		0xc7, 0xdd, 0x8c, 0xff, 0x4e, 0xa3, 0xc1, 0x68, 0xf9, 0x7f, 0x3f, 0xed,
		0xcf, 0x85, 0x77, 0x00, 0xfe, 0xe1, 0xe3, 0xfa, 0x7d, 0x56, 0x10, 0xb7,
		0xf1, 0x59, 0xff, 0x94, 0x44, 0x4e, 0x4c, 0xef, 0xef, 0xf7, 0xbf, 0xd3,
		0x28, 0xb0, 0x7c, 0xbd, 0x88, 0xd7, 0xfc, 0x58, 0xe7, 0x65, 0x19, 0x90,
		0x02, 0x40, 0x64, 0xa7, 0x11, 0x87, 0x2c, 0x10, 0x2e, 0xaa, 0x52, 0xc1,
		0x42, 0x5f, 0x8c, 0x7d, 0x6b, 0x37, 0xf4, 0x4c, 0x6c, 0x1a, 0x6f, 0xba,
		0xf5, 0xff, 0xa0, 0xd4, 0x82, 0x2b,
	}
	payload, _, err := ParseFrame(frame)
	if err != nil {
		t.Fatalf("ParseFrame: unexpected error: %v", err)
	}
	msg, err := DecodeMsg1004(payload)
	if err != nil {
		t.Fatalf("DecodeMsg1004: unexpected error: %v", err)
	}
	if msg.MessageType != 1004 {
		t.Fatalf("MessageType = %d, want 1004", msg.MessageType)
	}
	if msg.StationID != 0 {
		t.Fatalf("StationID = %d, want 0", msg.StationID)
	}
	if msg.GPSEpochTOWMs != 318945000 {
		t.Fatalf("GPSEpochTOWMs = %d, want 318945000", msg.GPSEpochTOWMs)
	}
	if len(msg.Satellites) != 11 {
		t.Fatalf("len(Satellites) = %d, want 11", len(msg.Satellites))
	}
	s0 := msg.Satellites[0]
	if s0.SatelliteID != 2 {
		t.Fatalf("Satellites[0].SatelliteID = %d, want 2", s0.SatelliteID)
	}
	checkFloat(t, "Satellites[0].L1PseudorangeM", s0.L1PseudorangeM, 282060.0, 1e-6)
	checkFloat(t, "Satellites[0].L1PhaserangeM", s0.L1PhaserangeM, -30.8545, 1e-6)
	if s0.L1LockTimeIndicator != 127 {
		t.Fatalf("Satellites[0].L1LockTimeIndicator = %d, want 127", s0.L1LockTimeIndicator)
	}
	checkFloat(t, "Satellites[0].L1PseudorangeAmbiguityM", s0.L1PseudorangeAmbiguityM, 22484434.35, 1e-2)
	checkFloat(t, "Satellites[0].L1CNRDbHz", s0.L1CNRDbHz, 43.0, 1e-6)
	if s0.L2CodeIndicator != 3 {
		t.Fatalf("Satellites[0].L2CodeIndicator = %d, want 3", s0.L2CodeIndicator)
	}
	checkFloat(t, "Satellites[0].L2MinusL1PseudorangeM", s0.L2MinusL1PseudorangeM, 8.34, 1e-6)
	checkFloat(t, "Satellites[0].L2PhaserangeM", s0.L2PhaserangeM, -44.145, 1e-6)
	checkFloat(t, "Satellites[0].L2CNRDbHz", s0.L2CNRDbHz, 31.25, 1e-6)
}
